import type { CredentialAcquisitionPanel, AcquisitionText } from "./acquisition.js";
import type { SecretInputRequest } from "./types.js";

const literal = (value: string): string => {
  if (!value || /[\r\n\0]/.test(value)) throw new Error("Unsafe acquisition text.");
  return "'" + value.replace(/'/g, "''") + "'";
};
const localized = (value: AcquisitionText): string => "(Get-AkcText " + literal(value.en) + " " + literal(value.ja) + ")";

/** One layout for every supported guide. Contains no value handling or provider branching. */
export function buildWindowsAcquisitionLayout(panel: CredentialAcquisitionPanel, request: SecretInputRequest): string[] {
  if (!("environment" in request)) throw new Error("Invalid acquisition slot.");
  const lines = [
    "Add-Type -TypeDefinition @'",
    "using System;",
    "using System.Drawing;",
    "using System.Windows.Forms;",
    "namespace ApiKeyCaseHumanPlane {",
    "  public class GuideLabel : Label {",
    "    public override Size GetPreferredSize(Size proposedSize) {",
    "      int width = Parent == null ? proposedSize.Width : Parent.ClientSize.Width - Parent.Padding.Horizontal - Margin.Horizontal;",
    "      var table = Parent as TableLayoutPanel; if (table != null) { int column = table.GetColumn(this); var columns = table.GetColumnWidths(); if (column >= 0 && column < columns.Length && columns[column] > 0) width = Math.Min(width, columns[column] - Margin.Horizontal); }",
    "      width = Math.Max(40, width);",
    "      Size measured; using (var graphics = CreateGraphics()) { measured = TextRenderer.MeasureText(graphics, Text.Length == 0 ? \" \" : Text, Font, new Size(Math.Max(40, width - Font.Height), Int32.MaxValue), TextFormatFlags.WordBreak | TextFormatFlags.TextBoxControl | TextFormatFlags.NoPrefix); }",
    "      return new Size(width, measured.Height + Padding.Vertical + 4);",
    "    }",
    "  }",
    "}",
    "'@ -ReferencedAssemblies System.Windows.Forms, System.Drawing",
    "function New-AkcStack {",
    "  $stack = New-Object System.Windows.Forms.TableLayoutPanel",
    "  $stack.ColumnCount = 1; $stack.RowCount = 0",
    "  $stack.AutoSize = $true; $stack.AutoSizeMode = [System.Windows.Forms.AutoSizeMode]::GrowAndShrink",
    "  $stack.Dock = [System.Windows.Forms.DockStyle]::Top",
    "  $stack.Margin = New-Object System.Windows.Forms.Padding(0)",
    "  [void]$stack.ColumnStyles.Add((New-Object System.Windows.Forms.ColumnStyle([System.Windows.Forms.SizeType]::Percent, 100)))",
    "  return $stack",
    "}",
    "function Add-AkcRow { param($Stack, $Control)",
    "  $row = $Stack.RowCount; $Stack.RowCount++",
    "  [void]$Stack.RowStyles.Add((New-Object System.Windows.Forms.RowStyle([System.Windows.Forms.SizeType]::AutoSize)))",
    "  $Stack.Controls.Add($Control, 0, $row)",
    "}",
    "function Add-AkcLabel { param($Stack, [string]$Text, [bool]$Bold = $false)",
    "  $label = New-Object ApiKeyCaseHumanPlane.GuideLabel",
    "  $label.AutoSize = $true; $label.Dock = [System.Windows.Forms.DockStyle]::Fill",
    "  $label.Margin = New-Object System.Windows.Forms.Padding(0, 2, 0, 5)",
    "  $label.Text = $Text; $label.UseMnemonic = $false",
    "  if ($Bold) { $label.Font = New-Object System.Drawing.Font($Stack.Font, [System.Drawing.FontStyle]::Bold) }",
    "  Add-AkcRow $Stack $label",
    "}",
    "function Set-AkcPrimary { param($Button)",
    "  if (-not [System.Windows.Forms.SystemInformation]::HighContrast) {",
    "    $Button.BackColor = [System.Drawing.Color]::FromArgb(24, 89, 62); $Button.ForeColor = [System.Drawing.Color]::White",
    "    $Button.FlatStyle = [System.Windows.Forms.FlatStyle]::Flat; $Button.FlatAppearance.BorderSize = 0; $Button.UseVisualStyleBackColor = $false",
    "  }",
    "}",
    "function Add-AkcCopyRow { param($Stack, [string]$Value, [string]$Caption)",
    "  $row = New-Object System.Windows.Forms.TableLayoutPanel",
    "  $row.ColumnCount = 2; $row.RowCount = 1; $row.AutoSize = $true; $row.Dock = [System.Windows.Forms.DockStyle]::Fill",
    "  $row.Padding = New-Object System.Windows.Forms.Padding(10, 8, 10, 8); $row.Margin = New-Object System.Windows.Forms.Padding(0, 0, 0, 6)",
    "  [void]$row.ColumnStyles.Add((New-Object System.Windows.Forms.ColumnStyle([System.Windows.Forms.SizeType]::Percent, 100)))",
    "  [void]$row.ColumnStyles.Add((New-Object System.Windows.Forms.ColumnStyle([System.Windows.Forms.SizeType]::AutoSize)))",
    "  if (-not [System.Windows.Forms.SystemInformation]::HighContrast) { $row.BackColor = [System.Drawing.Color]::FromArgb(231, 243, 234) }",
    "  $valueLabel = New-Object ApiKeyCaseHumanPlane.GuideLabel",
    "  $valueLabel.AutoSize = $true; $valueLabel.Dock = [System.Windows.Forms.DockStyle]::Fill; $valueLabel.UseMnemonic = $false",
    "  $valueLabel.Text = $Value; $valueLabel.Margin = New-Object System.Windows.Forms.Padding(0, 4, 8, 0)",
    "  $row.Controls.Add($valueLabel, 0, 0)",
    "  $copy = New-Object System.Windows.Forms.Button",
    "  $copy.AutoSize = $true; $copy.Padding = New-Object System.Windows.Forms.Padding(8, 4, 8, 4)",
    "  $copy.Text = (Get-AkcText 'Copy' 'コピー'); $copy.AccessibleName = $Caption + (Get-AkcText ' — Copy' 'をコピー')",
    "  $copy.Tag = $Value; $copy.UseVisualStyleBackColor = $true",
    "  $copy.Add_Click({ param($sender, $eventArgs)",
    "    try {",
    "      [System.Windows.Forms.Clipboard]::SetText([string]$sender.Tag)",
    "      $sender.Text = (Get-AkcText 'Copied' 'コピー済み')",
    "    } catch { $script:errorLabel.Text = (Get-AkcText 'Could not copy. Try again.' 'コピーできませんでした。もう一度お試しください。') }",
    "  })",
    "  $row.Controls.Add($copy, 1, 0); Add-AkcRow $Stack $row",
    "}",
    "$form = New-Object System.Windows.Forms.Form",
    "$script:form = $form",
    "$form.Text = (Get-AkcText 'API Key Case - Secret Input' 'API Key Case - シークレットの入力')",
    "$form.Font = New-Object System.Drawing.Font((Get-AkcText 'Segoe UI' 'Yu Gothic UI'), 12, [System.Drawing.GraphicsUnit]::Pixel)",
    "$form.AutoScaleMode = [System.Windows.Forms.AutoScaleMode]::None",
    "$script:guideDpi = 96",
    "$form.StartPosition = [System.Windows.Forms.FormStartPosition]::CenterScreen",
    "$form.FormBorderStyle = [System.Windows.Forms.FormBorderStyle]::FixedDialog",
    "$form.MaximizeBox = $false; $form.MinimizeBox = $false; $form.ShowInTaskbar = $true; $form.TopMost = $true",
    "$form.ClientSize = New-Object System.Drawing.Size(720, 660)",
    "if (-not [System.Windows.Forms.SystemInformation]::HighContrast) { $form.BackColor = [System.Drawing.Color]::FromArgb(247, 249, 247); $form.ForeColor = [System.Drawing.Color]::FromArgb(26, 50, 37) }",
    "$root = New-Object System.Windows.Forms.TableLayoutPanel",
    "$root.Dock = [System.Windows.Forms.DockStyle]::Fill; $root.ColumnCount = 1; $root.RowCount = 3",
    "$root.Padding = New-Object System.Windows.Forms.Padding(18, 14, 18, 14)",
    "[void]$root.ColumnStyles.Add((New-Object System.Windows.Forms.ColumnStyle([System.Windows.Forms.SizeType]::Percent, 100)))",
    "[void]$root.RowStyles.Add((New-Object System.Windows.Forms.RowStyle([System.Windows.Forms.SizeType]::AutoSize)))",
    "[void]$root.RowStyles.Add((New-Object System.Windows.Forms.RowStyle([System.Windows.Forms.SizeType]::Percent, 100)))",
    "[void]$root.RowStyles.Add((New-Object System.Windows.Forms.RowStyle([System.Windows.Forms.SizeType]::AutoSize)))",
    "$form.Controls.Add($root)",
    "$header = New-AkcStack; $root.Controls.Add($header, 0, 0)",
    "Add-AkcLabel $header " + localized(panel.title) + " $true",
    "Add-AkcLabel $header " + localized({ en: "App environment: " + request.environment + " | Project: " + request.projectId,
      ja: "対象環境：" + request.environment + "　プロジェクト：" + request.projectId }),
    "$scroll = New-Object System.Windows.Forms.Panel",
    "$scroll.Dock = [System.Windows.Forms.DockStyle]::Fill; $scroll.AutoScroll = $true; $scroll.TabStop = $false",
    "$scroll.Margin = New-Object System.Windows.Forms.Padding(0, 4, 0, 10)",
    "$root.Controls.Add($scroll, 0, 1)",
    "$guide = New-AkcStack; $scroll.Controls.Add($guide)",
    "Add-AkcLabel $guide " + localized({ en: "Registration project: " + request.projectDir, ja: "登録先のプロジェクト：" + request.projectDir }),
    "$acquisitionLink = New-Object System.Windows.Forms.LinkLabel",
    "$acquisitionLink.AutoSize = $true; $acquisitionLink.Dock = [System.Windows.Forms.DockStyle]::Fill",
    "$acquisitionLink.Margin = New-Object System.Windows.Forms.Padding(0, 4, 0, 8)",
    "$acquisitionLink.Text = " + localized(panel.linkText),
    "if (-not [System.Windows.Forms.SystemInformation]::HighContrast) { $acquisitionLink.LinkColor = [System.Drawing.Color]::FromArgb(24, 89, 62) }",
    "$acquisitionLink.Add_LinkClicked({ try { Start-Process " + literal(panel.linkUrl) + " } catch { $script:errorLabel.Text = " +
      localized({ en: "Could not open browser. Open " + panel.linkUrl + " manually.", ja: "ブラウザを開けません。" + panel.linkUrl + "を開いてください。" }) + " } })",
    "Add-AkcRow $guide $acquisitionLink"
  ];
  for (const section of panel.sections) {
    const name = "$section" + lines.length;
    if (section.collapsible) {
      lines.push(name + " = New-AkcStack", name + ".Visible = $false",
        "$toggle = New-Object System.Windows.Forms.Button",
        "$toggle.AutoSize = $true; $toggle.Dock = [System.Windows.Forms.DockStyle]::Fill",
        "$toggle.Text = " + localized(section.title), "$toggle.AccessibleName = $toggle.Text", "$toggle.Tag = " + name,
        "$toggle.Add_Click({ param($sender, $eventArgs) $sender.Tag.Visible = -not $sender.Tag.Visible; $sender.Text = if ($sender.Tag.Visible) { (Get-AkcText 'Hide details' '補足を閉じる') } else { $sender.AccessibleName } })",
        "Add-AkcRow $guide $toggle", "Add-AkcRow $guide " + name);
    } else {
      lines.push("Add-AkcLabel $guide " + localized(section.title) + " $true", name + " = $guide");
    }
    for (const entry of section.items) {
      lines.push("Add-AkcLabel " + name + " " + localized(entry.label) + " $true");
      if (entry.copyValue) lines.push("Add-AkcCopyRow " + name + " " + literal(entry.copyValue) + " " + localized(entry.label));
      // Copy rows show the exact metadata, with advisory explanations below it.
      if (!entry.copyValue || entry.value.en !== entry.copyValue || entry.value.ja !== entry.copyValue) {
        lines.push("Add-AkcLabel " + name + " " + localized(entry.value));
      }
    }
  }
  lines.push(
    "$footer = New-AkcStack; $root.Controls.Add($footer, 0, 2)",
    "Add-AkcLabel $footer (Get-AkcText '2. Paste and save the key' '2. キーを貼り付けて保存') $true",
    "Add-AkcLabel $footer " + localized({ en: request.name + " — stored directly in Windows Credential Manager.",
      ja: request.name + "をWindows資格情報マネージャーへ直接保存します。" }),
    "$input = New-Object System.Windows.Forms.TextBox; $script:input = $input",
    "$input.Dock = [System.Windows.Forms.DockStyle]::Fill; $input.UseSystemPasswordChar = $true; $input.MaxLength = 0",
    "$input.AccessibleName = (Get-AkcText 'API key — secure input' 'APIキーの入力欄')",
    "$input.Margin = New-Object System.Windows.Forms.Padding(0, 4, 0, 6)",
    "Add-AkcRow $footer $input",
    "Add-AkcLabel $footer (Get-AkcText 'Paste here only. Never in chat, files or command arguments. Account and permissions are not verified.' 'キーはこの欄だけに貼り、Chat・ファイル・コマンドの引数には貼らないでください。アカウント・権限は未検証です。')",
    "Add-AkcLabel $guide " + localized(panel.afterSave),
    "$errorLabel = New-Object ApiKeyCaseHumanPlane.GuideLabel; $script:errorLabel = $errorLabel",
    "$errorLabel.AutoSize = $true; $errorLabel.Dock = [System.Windows.Forms.DockStyle]::Fill",
    "$errorLabel.ForeColor = if ([System.Windows.Forms.SystemInformation]::HighContrast) { [System.Drawing.SystemColors]::WindowText } else { [System.Drawing.Color]::Firebrick }",
    "$errorLabel.AccessibleName = (Get-AkcText 'Input status' '入力結果')",
    "Add-AkcRow $footer $errorLabel",
    "$buttons = New-Object System.Windows.Forms.FlowLayoutPanel",
    "$buttons.AutoSize = $true; $buttons.Dock = [System.Windows.Forms.DockStyle]::Fill",
    "$buttons.FlowDirection = [System.Windows.Forms.FlowDirection]::RightToLeft; $buttons.WrapContents = $true",
    "$buttons.Margin = New-Object System.Windows.Forms.Padding(0, 6, 0, 0)",
    "$saveButton = New-Object System.Windows.Forms.Button; $cancelButton = New-Object System.Windows.Forms.Button",
    "$saveButton.Text = (Get-AkcText 'Save' '保存'); $cancelButton.Text = (Get-AkcText 'Cancel' 'キャンセル')",
    "$saveButton.AutoSize = $true; $cancelButton.AutoSize = $true",
    "$saveButton.Padding = New-Object System.Windows.Forms.Padding(16, 5, 16, 5); $cancelButton.Padding = $saveButton.Padding",
    "Set-AkcPrimary $saveButton",
    "$buttons.Controls.Add($cancelButton); $buttons.Controls.Add($saveButton); Add-AkcRow $footer $buttons",
    // AutoSize containers get tab order by data order. Input starts focused.
    "$header.TabIndex = 0; $scroll.TabIndex = 1; $guide.TabIndex = 0; $footer.TabIndex = 2",
    "$input.TabIndex = 0; $buttons.TabIndex = 1; $saveButton.TabIndex = 0; $cancelButton.TabIndex = 1",
    "function Update-AkcHeadings { param($Parent, $Dpi)",
    "  foreach ($control in $Parent.Controls) {",
    "    if ($control -is [ApiKeyCaseHumanPlane.GuideLabel] -and $control.Font.Bold) { $control.Font = New-Object System.Drawing.Font($script:form.Font, [System.Drawing.FontStyle]::Bold) }",
    "    Update-AkcHeadings $control $Dpi",
    "  }",
    "}",
    "function Fit-AkcGuide {",
    "  $work = [System.Windows.Forms.Screen]::FromControl($script:form).WorkingArea",
    "  $windowDpi = [ApiKeyCaseHumanPlane.Native]::GetDpiForWindow($script:form.Handle); if ($windowDpi -eq 0) { throw 'Display unavailable' }",
    "  $dpi = $windowDpi / 96",
    "  if ($windowDpi -ne $script:guideDpi) {",
    "    $factor = $windowDpi / $script:guideDpi; $script:guideDpi = $windowDpi",
    "    $script:form.Scale((New-Object System.Drawing.SizeF($factor, $factor)))",
    "    $script:form.Font = New-Object System.Drawing.Font((Get-AkcText 'Segoe UI' 'Yu Gothic UI'), (12 * $dpi), [System.Drawing.GraphicsUnit]::Pixel)",
    "  }",
    "  Update-AkcHeadings $script:form $dpi",
    "  $header.Controls[0].Font = New-Object System.Drawing.Font($script:form.Font.FontFamily, (14 * $dpi), [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)",
    "  $width = [Math]::Min([int](720 * $dpi), $work.Width - [int](32 * $dpi))",
    "  $script:form.ClientSize = New-Object System.Drawing.Size($width, $script:form.ClientSize.Height)",
    "  $script:form.PerformLayout()",
    "  $desired = $header.Height + $footer.Height + $guide.GetPreferredSize((New-Object System.Drawing.Size($scroll.ClientSize.Width, 0))).Height + $root.Padding.Vertical + $scroll.Margin.Vertical",
    "  $chrome = $script:form.Height - $script:form.ClientSize.Height",
    "  $height = [Math]::Min($desired, $work.Height - $chrome - [int](24 * $dpi))",
    "  if ($height -lt $header.Height + $footer.Height + [int](60 * $dpi)) { throw 'Display unavailable' }",
    "  $script:form.ClientSize = New-Object System.Drawing.Size($width, $height)",
    "  $script:form.Left = $work.Left + [int](($work.Width - $script:form.Width) / 2)",
    "  $script:form.Top = $work.Top + [int](($work.Height - $script:form.Height) / 2)",
    "}",
    "$form.Add_Shown({ try { Fit-AkcGuide } catch { $script:resultCode = 10; $script:form.Close() } })",
    "$form.Add_LocationChanged({ if ($script:form.Visible -and [ApiKeyCaseHumanPlane.Native]::GetDpiForWindow($script:form.Handle) -ne $script:guideDpi) { try { Fit-AkcGuide } catch { $script:resultCode = 10; $script:form.Close() } } })",
    "$form.Add_DpiChanged({ try { Fit-AkcGuide } catch { $script:resultCode = 10; $script:form.Close() } })"
  );
  return lines;
}
